const block = (b) => h('section', { class: 'card' }, h('h2', null, b.t), h('ol', null, ...b.steps.map((s) => h('li', { style: 'margin:6px 0' }, s))));

export async function render(root) {
  // المفتاح مطفأ: غير مسؤول الشعبة يرى رسالة «مطفأ» الموحدة فقط. ومسؤول الشعبة يرى الصفحة معاينةً (نص ثابت بلا طلب للخادم) وفوقها الرسالة نفسها
  if (!S.profile?.ops?.help) {
    const { offNotice } = await import('./off_notice.js');
    const off = offNotice('feature.help', { what: 'صفحة «المساعدة» مطفأة الآن.' });
    if (!S.profile?.is_division_head) { root.append(off); return; }
    root.append(off, h('p', { class: 'small', style: 'font-weight:700' }, 'أنت تراها الآن معاينةً، وغيرك لا يراها حتى يوم البدء.'));
  }
  const mine = [...new Set((S.profile?.assignments || []).map((a) => a.role))].filter((r) => ROLES[r]);
  root.append(h('p', { class: 'muted small' }, 'خطوات قصيرة لما تحتاجه في دورك. إن لم تجد ما تبحث عنه فأرسل «بلاغ مشكلة» واكتب سؤالك.'),
    ...mine.map((r) => block(ROLES[r])), block(COMMON), block(REPORT));
}
