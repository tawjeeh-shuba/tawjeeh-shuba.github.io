export async function render(root) {
  const live = h('div', { class: 'row', style: 'gap:6px;flex-wrap:wrap' }, badge('جارٍ قراءة الجاهزية…', 'gray'));
  root.append(card(
    h('div', { class: 'row between' }, h('h2', { style: 'margin:0' }, 'ابدأ التجربة'), live),
    h('p', { class: 'muted small' }, 'ثلاثة أقسام: ما هو جاهز، وما بقي عليك (بالترتيب)، وخطوات يوم البدء لأي تاريخ تختاره.')));

  root.append(card(h('h3', { style: 'margin-top:0' }, 'ما هو جاهز'),
    h('ul', { class: 'small', style: 'list-style:none;margin:0;padding:0;line-height:1.9' },
      READY.map((t) => h('li', null, h('span', { style: 'color:var(--ok, #1a7f37);font-weight:700;margin-inline-end:6px' }, '✓'), t)))));

  root.append(card(h('h3', { style: 'margin-top:0' }, `ما بقي عليك (${nf(TODO.length)} بنود بالترتيب)`),
    ...TODO.map((x, i) => h('div', { class: 'list-item' }, h('b', null, `${nf(i + 1)}. ${x.t}`), steps(x.s.map(iso))))));

  root.append(card(h('h3', { style: 'margin-top:0' }, 'يوم البدء (أي تاريخ تختاره)'),
    h('ol', { class: 'small', style: 'margin:0;padding-inline-start:20px;line-height:1.9' },
      DAY.map(([t, d]) => h('li', null, h('b', null, t + ': '), d)))));

  // الأرقام الحية: كم بنداً جاهزاً في «جاهزية التجربة» و«الاستعداد التشغيلي» الآن
  Promise.allSettled([rpc('rpc_trial_readiness'), rpc('rpc_ops_readiness')]).then(([a, b]) => {
    const out = [];
    if (a.status === 'fulfilled') out.push(badge(`الجاهزية: ${nf(a.value.ready)} من ${nf(a.value.total)}`, a.value.ready === a.value.total ? 'ok' : 'warn'));
    if (b.status === 'fulfilled') { const ok = b.value.items.filter((x) => x.ok).length; out.push(badge(`التشغيل: ${nf(ok)} من ${nf(b.value.items.length)}`, ok === b.value.items.length ? 'ok' : 'warn')); }
    live.replaceChildren(...(out.length ? out : [badge('تعذّرت قراءة الجاهزية', 'gray')]));
  });
}
